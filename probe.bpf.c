// PHIPS collector, kernel side (schema v3).
//
// Design: everything is built on TRACEPOINTS, the stable kernel tracing interface, so the same
// object file runs on any kernel >= 5.8 with BTF (Fedora, Debian/Kali, Ubuntu, RHEL 9, ...),
// including kernels built without kprobes or fentry. Falco's "modern" eBPF probe uses the same idea.
//
//   tp_btf/sys_enter          one hook for ALL syscalls; we pick the few we care about by number
//   tp_btf/sys_exit           same, at syscall return: we need the result of open/accept
//   tp_btf/sched_process_fork new process created (threads are filtered out)
//   tp_btf/sched_process_exec program replaced successfully (failed execs never reach it)
//   tracepoint sched_process_exit  process exit (only when the whole process is gone)
//
// Paths and peer addresses are resolved INSIDE the kernel, from the kernel's own file and socket
// objects, at the moment of the event. User space never has to look at /proc to find out what a
// file descriptor was, so short-lived processes and closed fds are no longer a problem.

// vmlinux.h (generated by a recent bpftool) also declares the kernel's kfuncs, e.g.
// bpf_stream_vprintk(). Newer libbpf headers (bpf_helpers.h) declare some of the same kfuncs with
// slightly different types, so the two collide ("conflicting types for 'bpf_stream_vprintk'").
// This probe uses no kfuncs, so we skip vmlinux.h's kfunc block. Must come BEFORE the include.
#define BPF_NO_KFUNC_PROTOTYPES
#include "vmlinux.h"
#include <bpf/bpf_helpers.h>
#include <bpf/bpf_tracing.h>
#include <bpf/bpf_core_read.h>
#include <bpf/bpf_endian.h>

